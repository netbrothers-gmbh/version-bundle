namespace NetBrothers\VersionBundle\Services\Sql;

use Doctrine\DBAL\Exception;
use NetBrothers\VersionBundle\Services\DatabaseConnectionProvider;

/**
 * Executes generated SQL statements against the active Doctrine DBAL connection.
 */
final readonly class ExecuteService
{
    public function __construct(
        private DatabaseConnectionProvider $connectionProvider,
    ) {
    }

    /**
     * Executes the assembled queries.
     *
     * @param string[] $sql SQL queries generated by the GenerateService.
     * @throws Exception|\RuntimeException
     */
    public function execute(array $sql = []): void
    {
        if ($sql === []) {
            return;
        }

        $connection = $this->connectionProvider->getConnection();
        foreach ($sql as $query) {
            $connection->executeStatement($query);
        }
    }
}
