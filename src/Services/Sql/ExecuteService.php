namespace NetBrothers\VersionBundle\Services\Sql;

use Doctrine\DBAL\Connection;
use Doctrine\DBAL\Exception;
use Doctrine\DBAL\Platforms\MariaDBPlatform;
use Doctrine\DBAL\Platforms\MySQLPlatform;
use Doctrine\ORM\EntityManagerInterface;

/**
 * Execute SQL on connection.
 */
final class ExecuteService
{
    private Connection $connection;

    /**
     * @throws \Exception|Exception
     */
    public function __construct(EntityManagerInterface $entityManager)
    {
        $this->connection = $entityManager->getConnection();
        $platform = $this->connection->getDatabasePlatform();

        if (!($platform instanceof MySQLPlatform || $platform instanceof MariaDBPlatform)) {
            throw new \Exception(sprintf('Unsupported database platform: %s', get_class($platform)));
        }
    }

    /**
     * Executes the assembled queries.
     *
     * @param string[] $sql SQL queries priorly generated by the `GenerateService`.
     * @throws Exception
     */
    public function execute(array $sql = []): void
    {
        if (empty($sql)) {
            return;
        }
        foreach ($sql as $query) {
            $this->connection->executeStatement($query);
        }
    }
}
